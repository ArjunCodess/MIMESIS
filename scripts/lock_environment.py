"""Pin the tested Python dependency closure, excluding unrelated user packages."""

from importlib.metadata import distribution
from pathlib import Path
import tomllib
from packaging.requirements import Requirement

root = Path(__file__).resolve().parents[1]
project = tomllib.loads((root / "pyproject.toml").read_text())["project"]
pending = project["dependencies"] + project["optional-dependencies"]["test"]
resolved = {}
while pending:
    requirement = Requirement(pending.pop())
    if requirement.marker and not requirement.marker.evaluate({"extra": ""}):
        continue
    dist = distribution(requirement.name)
    name = dist.metadata["Name"]
    if name.lower() in resolved:
        continue
    resolved[name.lower()] = f"{name}=={dist.version}"
    pending.extend(dist.requires or [])
(root / "requirements.lock").write_text(
    "# Tested Python dependency closure. Generated by scripts/lock_environment.py\n"
    + "\n".join(resolved[key] for key in sorted(resolved))
    + "\n",
    encoding="utf-8",
)
print(f"Pinned {len(resolved)} distributions")
